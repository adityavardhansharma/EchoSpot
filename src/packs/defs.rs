/// The typed stand-ins, by path inside the pack.
pub fn stubs() -> Vec<(String, String)> {
    let mut ui = String::from("--!strict\n-- A typed stand-in for @echo/ui. The host provides the real one.\nexport type Block = { _ui: string, [string]: any }\ntype Props = { [string]: any }\nlocal ui = {}\n");
    for (name, about, props) in blocks::COMPONENTS {
        ui.push_str(&format!("-- {about}. Props: {props}\nfunction ui.{name}(props: Props): Block return {{ _ui = {name:?} }} end\n"));
    }
    for name in ["row", "col", "box", "glass"] {
        ui.push_str(&format!("function ui.{name}(props: any, children: {{ any }}?): Block return {{ _ui = {name:?} }} end\n"));
    }
    ui.push_str("function ui.text(content: any, props: Props?): Block return { _ui = \"text\" } end\n");
    ui.push_str("function ui.spacer(props: Props?): Block return { _ui = \"spacer\" } end\n");
    ui.push_str("function ui.icon(name: string, props: Props?): Block return { _ui = \"icon\" } end\n");
    ui.push_str("function ui.image(source: string, props: Props?): Block return { _ui = \"image\" } end\n");
    ui.push_str("function ui.input(props: Props?): Block return { _ui = \"input\" } end\n");
    ui.push_str("function ui.markdown(source: any, props: Props?): Block return { _ui = \"markdown\" } end\n");
    ui.push_str("function ui.code(source: string, props: Props?): Block return { _ui = \"code\" } end\n");
    ui.push_str("function ui.chart(props: Props): Block return { _ui = \"chart\" } end\n");
    ui.push_str("function ui.fx(effects: { [string]: any }, child: Block): Block return { _ui = \"fx\" } end\n");
    ui.push_str("function ui.each(items: any, build: (any, number) -> any): { any } return {} end\nreturn ui\n");

    let mut t = String::from("--!strict\n-- A typed stand-in for @echo/types. The host provides the real one.\nexport type Type = { type: string, optional: (self: Type) -> Type, default: (self: Type, value: any) -> Type, describe: (self: Type, label: string) -> Type }\nlocal function make(kind: string): Type\n\tlocal self = { type = kind } :: any\n\tself.optional = function() return self end\n\tself.default = function() return self end\n\tself.describe = function() return self end\n\treturn self\nend\nlocal t = {}\n");
    for (name, _) in types::CORE.iter().filter(|(n, _)| !matches!(*n, "list" | "record" | "enum" | "series")) {
        t.push_str(&format!("function t.{name}(): Type return make({name:?}) end\n"));
    }
    t.push_str("function t.series(): Type return make(\"series\") end\nfunction t.list(of: Type): Type return make(\"list\") end\nfunction t.record(name: any, fields: { [string]: Type }?): Type return make(\"record\") end\nfunction t.enum(first: any, ...: string): Type return make(\"enum\") end\nfunction t.optional(of: Type): Type return of end\nreturn t\n");
    vec![(".echo/init.luau".into(), STUB_ECHO.to_string()), (".echo/ui.luau".into(), ui), (".echo/types.luau".into(), t)]
}

/// Writes the definitions, the stand-ins and `.luaurc` into a pack's folder. Returns what changed.
pub fn write(rt: &Runtime, pack: &str, dir: &Path) -> Vec<String> {
    let mut files = stubs();
    files.push(("echospot.d.luau".into(), definitions(rt, pack)));
    if !dir.join(".luaurc").exists() {
        files.push((".luaurc".into(), LUAURC.to_string()));
    }
    let mut changed = Vec::new();
    for (name, text) in files {
        let path = dir.join(&name);
        if std::fs::read_to_string(&path).ok().as_deref() == Some(text.as_str()) {
            continue;
        }
        if let Some(parent) = path.parent() {
            let _ = std::fs::create_dir_all(parent);
        }
        if std::fs::write(&path, text).is_ok() {
            changed.push(name);
        }
    }
    changed
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn definitions_name_what_can_be_called() {
        let rt = Runtime::ephemeral();
        let text = definitions(&rt, "nobody");
        assert!(text.contains("[\"calc.convert\"]: ({ amount: number, from: string, to: string }) -> any"), "{text}");
        assert!(text.contains("export type Money = { amount: number, currency: string }"));
        // A built-in that needs a grant isn't offered to a pack that never asked.
        assert!(!text.contains("[\"notes.create\"]") && !text.contains("[\"http.get\"]"));
        assert!(text.contains("call: (self: Cx, address: string, input: any?) -> any"));
    }

    #[test]
    fn the_stand_ins_are_real_luau() {
        let lua = rune_luau::mlua::Lua::new();
        for (name, text) in stubs() {
            lua.load(&text).set_name(name.clone()).into_function().unwrap_or_else(|e| panic!("{name}: {e}"));
            // Every name the real module answers to is in its stand-in.
            if name.ends_with("ui.luau") {
                for real in crate::packs::vm::ui_names() {
                    assert!(text.contains(&format!("function ui.{real}(")), "ui.{real} is missing from the stand-in");
                }
            }
            if name.ends_with("init.luau") {
                for real in crate::packs::vm::ECHO_NAMES {
                    assert!(text.contains(&format!("echo.{real}")), "echo.{real} is missing from the stand-in");
                }
            }
        }
        assert!(serde_json::from_str::<serde_json::Value>(LUAURC).is_ok());
    }
}
