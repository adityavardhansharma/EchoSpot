//! Types before running. From the same declarations the host runs on, this writes what an editor
//! and a type checker need: `echospot.d.luau` (every address the pack may call, with its exact
//! input and output types), typed stand-ins for `@echo`, `@echo/ui` and `@echo/types`, and the
//! `.luaurc` that makes luau-lsp resolve them the way the host does.

use std::path::Path;

use super::api;
use super::blocks;
use super::runtime::Runtime;
use super::types::{self, Type};

/// A Luau type for a schema, with record names kept where they have one.
fn luau(t: &Type) -> String {
    t.luau()
}

fn input_type(input: &Type) -> String {
    if input.fields.is_empty() { "{}?".to_string() } else { luau(input) }
}

/// The addresses a pack may call: its own, the free built-ins, and what `calls` names.
pub fn callable(rt: &Runtime, pack: &str) -> Vec<(String, Type, Option<Type>, String)> {
    let declared: Vec<String> = rt.packs.get(pack).map(|p| p.manifest.permissions.calls.clone()).unwrap_or_default();
    let perms = rt.packs.get(pack).map(|p| p.manifest.permissions.clone()).unwrap_or_default();
    let mut out = Vec::new();
    for p in rt.packs.values() {
        for (name, a) in p.index.abilities.iter().filter(|(_, a)| a.has_run) {
            let address = format!("{}.{name}", p.id);
            if p.id == pack || declared.contains(&address) {
                out.push((address, a.input.clone(), a.output.clone(), a.title.clone()));
            }
        }
    }
    for spec in rt.specs() {
        use super::builtins::Gate;
        let may = match spec.gate {
            Gate::Free => true,
            Gate::Calls => declared.contains(&spec.address),
            Gate::Clipboard(level) => perms.clipboard == "read" || perms.clipboard == level,
            Gate::Net => !perms.net.is_empty(),
            Gate::Run => !perms.run.is_empty(),
            Gate::Ai => perms.ai.is_some(),
            Gate::Files => true,
        };
        if may {
            out.push((spec.address.clone(), spec.input.clone(), Some(spec.output.clone()), spec.title.clone()));
        }
    }
    out.sort_by(|a, b| a.0.cmp(&b.0));
    out
}

/// `echospot.d.luau` for a pack.
pub fn definitions(rt: &Runtime, pack: &str) -> String {
    let mut out = format!("-- echospot.d.luau: generated by EchoSpot {} for the pack \"{pack}\". Don't edit; `echospot dev check` writes it again.\n-- API version {}.\n\n", env!("CARGO_PKG_VERSION"), super::API);
    out.push_str("-- Core types, as values of each are shaped.\n");
    for (name, shape) in types::CORE.iter().filter(|(n, _)| !matches!(*n, "list" | "record" | "enum" | "any")) {
        let pascal: String = name[..1].to_uppercase() + &name[1..];
        out.push_str(&format!("export type {pascal} = {}\n", shape.replace('…', "")));
    }
    out.push_str("\nexport type Kind = \"read\" | \"effect\" | \"final\"\n");
    out.push_str("export type Intent = ");
    out.push_str(&blocks::INTENTS.iter().map(|i| format!("{i:?}")).collect::<Vec<_>>().join(" | "));
    out.push_str("\nexport type Look = ");
    out.push_str(&super::looks::NAMES.iter().map(|l| format!("{l:?}")).collect::<Vec<_>>().join(" | "));
    out.push_str("\nexport type Resource<T> = { _resource: true, state: \"pending\" | \"ok\" | \"error\", value: T?, error: string? }\n");
    out.push_str("export type Block = { _ui: string, [string]: any }\n");
    out.push_str("export type Error = { code: string, message: string, at: string?, nearest: { string }?, learn: string? }\n\n");

    // Record types the pack and what it calls declare by name.
    let calls = callable(rt, pack);
    let mut named: Vec<(String, String)> = Vec::new();
    fn collect(t: &Type, named: &mut Vec<(String, String)>) {
        if t.kind == "record" && !t.name.is_empty() && !named.iter().any(|(n, _)| *n == t.name) {
            named.push((t.name.clone(), t.luau()));
        }
        if let Some(of) = &t.of {
            collect(of, named);
        }
        for field in t.fields.values() {
            collect(field, named);
        }
    }
    for (_, input, output, _) in &calls {
        collect(input, &mut named);
        if let Some(output) = output {
            collect(output, &mut named);
        }
    }
    if !named.is_empty() {
        out.push_str("-- Records declared with t.record(\"name\", { … }).\n");
        for (name, shape) in &named {
            out.push_str(&format!("export type Record_{} = {shape}\n", name.replace('-', "_")));
        }
        out.push('\n');
    }

    out.push_str("-- Every address this pack may call, with what it takes and gives back.\n-- Not here? It needs `calls = [\"…\"]` in pack.toml, or it doesn't exist: `echospot dev api search <words>`.\nexport type Calls = {\n");
    for (address, input, output, title) in &calls {
        out.push_str(&format!("\t-- {title}\n\t[{address:?}]: ({}) -> {},\n", input_type(input), output.as_ref().map(luau).unwrap_or_else(|| "any".into())));
    }
    out.push_str("}\n\n");

    out.push_str("-- The context every pack function gets.\nexport type Cx = {\n\tpack: string,\n\tdata: string,\n");
    for (name, signature, about) in api::CX.iter().filter(|(n, ..)| !matches!(*n, "pack" | "data")) {
        let ty = match *name {
            "call" => "(self: Cx, address: string, input: any?) -> any",
            "try" => "(self: Cx, address: string, input: any?) -> (boolean, any)",
            "load" => "(self: Cx, address: string, input: any?) -> Resource<any>",
            "store" => "(self: Cx, name: string) -> any",
            "storeAt" => "(self: Cx, name: string, time: number) -> any",
            "put" => "(self: Cx, name: string, value: any) -> ()",
            "push" | "replace" => "(self: Cx, address: string, args: any?) -> ()",
            "pop" => "(self: Cx) -> ()",
            "toast" => "(self: Cx, text: string, intent: Intent?) -> ()",
            "hud" => "(self: Cx, text: string) -> ()",
            "dry" => "(self: Cx) -> boolean",
            _ => "(self: Cx, ...any) -> ()",
        };
        out.push_str(&format!("\t-- {signature}: {about}\n\t{name}: {ty},\n"));
    }
    out.push_str("}\n\n-- What a surface draws from.\nexport type View = { target: string, args: { [string]: any }, query: string, size: { number }?, dark: boolean?, tab: string? }\n\n");

    if let Some(p) = rt.packs.get(pack) {
        if !p.index.stores.is_empty() {
            out.push_str("-- This pack's stores: cx:store(name), cx:put(name, value).\nexport type Stores = {\n");
            for (name, decl) in &p.index.stores {
                out.push_str(&format!("\t{name}: {},\n", decl.ty.as_ref().map(luau).unwrap_or_else(|| "any".into())));
            }
            out.push_str("}\n\n");
        }
    }
    out.push_str("-- Components: ui.<Name> { … } returns a Block.\n");
    for (name, about, props) in blocks::COMPONENTS {
        out.push_str(&format!("-- ui.{name}: {about}. Props: {props}\n"));
    }
    out
}

